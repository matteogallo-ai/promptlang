test.if(pythonAvailable)("generated Python parses with ast.parse (classify-ticket)", async () => {
  const source = await Bun.file("docs/examples/classify-ticket.prompt").text();
  const ast = parse(tokenize(source));
  const generated = compilePython(ast, "classify-ticket.prompt");
  const runtime = getPythonRuntimeSource();

  const tmpDir = "/tmp/promptlang-python-test";
  await mkdir(tmpDir, { recursive: true });
  await writeFile(`${tmpDir}/classify_ticket.py`, generated);
  await writeFile(`${tmpDir}/promptlang_runtime.py`, runtime);
  await writeFile(`${tmpDir}/__init__.py`, "");

  try {
    // 1. py_compile — syntax check
    const compile = Bun.spawnSync(["python3", "-m", "py_compile", `${tmpDir}/classify_ticket.py`]);
    if (compile.exitCode !== 0) {
      const stderr = new TextDecoder().decode(compile.stderr);
      throw new Error(`py_compile failed:\n${stderr}\n\nGenerated:\n${generated}`);
    }
    expect(compile.exitCode).toBe(0);

    // 2. ast.parse — both files are syntactically valid Python
    const importTest = `
import ast
with open('${tmpDir}/classify_ticket.py') as f:
    ast.parse(f.read())
with open('${tmpDir}/promptlang_runtime.py') as f:
    ast.parse(f.read())
print("OK")
`.trim();
    const result = Bun.spawnSync(["python3", "-c", importTest]);
    if (result.exitCode !== 0) {
      const stderr = new TextDecoder().decode(result.stderr);
      throw new Error(`ast.parse failed:\n${stderr}`);
    }
    expect(result.exitCode).toBe(0);
  } finally {
    await rm(tmpDir, { recursive: true, force: true });
  }
});

