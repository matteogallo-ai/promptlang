/**
 * Measures the compiler pipeline and writes docs/benchmarks.md.
 *
 * Usage: bun run bench            # print the report
 *        bun run bench --write    # also overwrite docs/benchmarks.md
 *
 * Numbers depend on the machine; the report records which machine produced
 * them so a reader can tell when they are stale.
 */
import { cpus, platform, release, totalmem } from "node:os";
import { join } from "node:path";
import { compile, compilePython, parse, tokenize } from "../src/index";

const ROOT = join(import.meta.dir, "..");
const EXAMPLES = ["classify-ticket", "extract-invoice", "summarize-and-translate"];
const HOT_ITERATIONS = 200;
const HOT_WARMUP = 10;
const CLI_RUNS = 10;
const CLI_WARMUP = 2;

function perIterationMs(fn: () => void): number {
  for (let i = 0; i < HOT_WARMUP; i++) fn();
  const start = performance.now();
  for (let i = 0; i < HOT_ITERATIONS; i++) fn();
  return (performance.now() - start) / HOT_ITERATIONS;
}

function cliSamplesMs(args: string[]): number[] {
  const cmd = [process.execPath, "run", join(ROOT, "src/cli/cli.ts"), ...args];
  for (let i = 0; i < CLI_WARMUP; i++) Bun.spawnSync(cmd, { cwd: ROOT });
  const samples: number[] = [];
  for (let i = 0; i < CLI_RUNS; i++) {
    const start = performance.now();
    const result = Bun.spawnSync(cmd, { cwd: ROOT });
    if (result.exitCode !== 0)
      throw new Error(`bench: '${args.join(" ")}' exited ${result.exitCode}`);
    samples.push(performance.now() - start);
  }
  return samples.sort((a, b) => a - b);
}

const ms = (n: number) => `${n.toFixed(2)} ms`;

async function hotLoopTable(): Promise<string[]> {
  const rows = [
    "| Example | Source bytes | Tokens | `tokenize` | `parse` (incl. tokenize) | `compile` (TS) | `compilePython` |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
  ];
  for (const name of EXAMPLES) {
    const source = await Bun.file(join(ROOT, "docs/examples", `${name}.prompt`)).text();
    const ast = parse(tokenize(source));
    rows.push(
      `| ${name} | ${Buffer.byteLength(source)} | ${tokenize(source).length} | ${ms(perIterationMs(() => tokenize(source)))} | ${ms(perIterationMs(() => parse(tokenize(source))))} | ${ms(perIterationMs(() => compile(ast, name)))} | ${ms(perIterationMs(() => compilePython(ast, name)))} |`
    );
  }
  return rows;
}

function cliTable(outDir: string): string[] {
  const commands: string[][] = [
    ["version"],
    ["parse", "docs/examples/classify-ticket.prompt"],
    ["analyze", "docs/examples/"],
    ["compile", "docs/examples/classify-ticket.prompt", "--out", outDir],
    ["compile", "docs/examples/*.prompt", "--out", outDir, "--target", "python"],
  ];
  const rows = ["| Command | Median | Min | Max |", "| --- | ---: | ---: | ---: |"];
  for (const args of commands) {
    const s = cliSamplesMs(args);
    const shown = args.map((a) => (a === outDir ? "<tmp>" : a)).join(" ");
    rows.push(
      `| \`${shown}\` | ${ms(s[Math.floor(s.length / 2)]!)} | ${ms(s[0]!)} | ${ms(s[s.length - 1]!)} |`
    );
  }
  return rows;
}

async function report(): Promise<string> {
  const outDir = join(process.env.TMPDIR ?? "/tmp", "promptlang-bench-out");
  const cpu = cpus()[0]?.model ?? "unknown CPU";
  return [
    "# Benchmarks",
    "",
    "Generated by `bun run bench --write` (`benchmarks/bench.ts`). Do not edit by hand;",
    "re-run the script instead. Timings are wall-clock on the machine below and are",
    "only comparable with runs on similar hardware.",
    "",
    `- Machine: ${cpu}, ${cpus().length} logical cores, ${Math.round(totalmem() / 2 ** 30)} GB RAM`,
    `- OS: ${platform()} ${release()}`,
    `- Runtime: Bun ${Bun.version}`,
    `- Date: ${new Date().toISOString().slice(0, 10)}`,
    "",
    "## In-process pipeline",
    "",
    `Mean per iteration over ${HOT_ITERATIONS} iterations after ${HOT_WARMUP} warm-up iterations.`,
    "",
    ...(await hotLoopTable()),
    "",
    "## CLI end to end",
    "",
    `Process spawn to exit, ${CLI_RUNS} runs after ${CLI_WARMUP} warm-up runs. This includes`,
    "Bun start-up, which dominates for single files.",
    "",
    ...cliTable(outDir),
    "",
  ].join("\n");
}

const text = await report();
console.log(text);
if (process.argv.includes("--write")) {
  await Bun.write(join(ROOT, "docs/benchmarks.md"), text);
  console.error("wrote docs/benchmarks.md");
}
