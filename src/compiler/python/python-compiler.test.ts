describe("Python compiler — type declarations", () => {
  test("enum type produces Literal + _VALUES list", () => {
    const out = compile(`type Status = enum { active, inactive, pending }`);
    expect(out).toContain(`Status = Literal["active", "inactive", "pending"]`);
    expect(out).toContain(`_STATUS_VALUES`);
    expect(out).toContain(`"active", "inactive", "pending"`);
  });

  test("struct type produces TypedDict class", () => {
    const out = compile(`type Invoice = struct { amount: number, vendor: string }`);
    expect(out).toContain("class Invoice(TypedDict):");
    expect(out).toContain("    amount: float");
    expect(out).toContain("    vendor: str");
  });

  test("struct optional field uses NotRequired", () => {
    const out = compile(`type Invoice = struct { amount: number, ref?: string }`);
    expect(out).toContain("    ref: NotRequired[str]");
  });
});

