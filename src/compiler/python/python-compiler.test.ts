describe("Python compiler — chains", () => {
  test("simple chain with one step compiles", () => {
    const out = compile(`
@version "1.0.0"
prompt summarize(text: string) -> string { user: "Summarize: {{text}}" }
chain process(text: string) -> string {
  step summary = summarize(text: text)
  return summary
}`);
    expect(out).toContain("async def process(");
    expect(out).toContain("summary = await summarize(");
    expect(out).toContain("return summary");
  });

  test("chain input uses dict access input['param']", () => {
    const out = compile(`
@version "1.0.0"
prompt greet(name: string) -> string { user: "Hi {{name}}" }
chain run(name: string) -> string {
  step result = greet(name: name)
  return result
}`);
    expect(out).toContain(`"name": input["name"]`);
  });

  test("chain TypedDict is PascalCase + Input", () => {
    const out = compile(`
@version "1.0.0"
prompt greet(name: string) -> string { user: "Hi {{name}}" }
chain run_all(name: string) -> string {
  step r = greet(name: name)
  return r
}`);
    expect(out).toContain("class RunAllInput(TypedDict):");
  });

  test("boolean literal in chain is True/False (Python)", () => {
    const out = compile(`
@version "1.0.0"
prompt check(flag: boolean) -> string { user: "test" }
chain run() -> string {
  step r = check(flag: true)
  return r
}`);
    expect(out).toContain("True");
  });
});

