describe("Python compiler — prompt declarations", () => {
  test("prompt with no params generates empty TypedDict", () => {
    const out = compile(`@version "1.0.0"\nprompt greet() -> string { user: "Hi" }`);
    expect(out).toContain("class GreetInput(TypedDict):");
    expect(out).toContain("    pass");
  });

  test("prompt with one string param → TypedDict field as str", () => {
    const out = compile(`@version "1.0.0"\nprompt greet(name: string) -> string { user: "Hi {{name}}" }`);
    expect(out).toContain("class GreetInput(TypedDict):");
    expect(out).toContain("    name: str");
  });

  test("prompt with multiple params → all fields in TypedDict", () => {
    const out = compile(`@version "1.0.0"\nprompt calc(x: number, y: boolean) -> string { user: "test" }`);
    expect(out).toContain("    x: float");
    expect(out).toContain("    y: bool");
  });

  test("metadata @model appears in META constant", () => {
    const out = compile(`@model claude-haiku-4-5\nprompt greet() -> string { user: "Hi" }`);
    expect(out).toContain(`GREET_META`);
    expect(out).toContain(`"model": "claude-haiku-4-5"`);
  });

  test("metadata @temperature appears in META constant", () => {
    const out = compile(`@temperature 0.5\nprompt greet() -> string { user: "Hi" }`);
    expect(out).toContain(`"temperature": 0.5`);
  });

  test("META constant is SCREAMING_SNAKE_CASE", () => {
    const out = compile(`@version "1.0.0"\nprompt classify_ticket() -> string { user: "test" }`);
    expect(out).toContain("CLASSIFY_TICKET_META");
  });

  test("function is async def", () => {
    const out = compile(`@version "1.0.0"\nprompt greet() -> string { user: "Hi" }`);
    expect(out).toContain("async def greet(");
  });

  test("function has return type annotation", () => {
    const out = compile(`@version "1.0.0"\nprompt greet() -> string { user: "Hi" }`);
    expect(out).toContain(") -> str:");
  });

  test("enum return type generates validation against _VALUES", () => {
    const out = compile(`
type Cat = enum { bug, feature }
prompt classify() -> Cat { user: "test" }`);
    expect(out).toContain("_CAT_VALUES");
    expect(out).toContain("if raw not in");
  });

  test("struct return type generates JSON parse validation", () => {
    const out = compile(`
type Invoice = struct { amount: number }
prompt extract() -> Invoice { user: "test" }`);
    expect(out).toContain("_json.loads(raw)");
    expect(out).toContain("JSONDecodeError");
  });

  test("number return type generates float() conversion", () => {
    const out = compile(`@version "1.0.0"\nprompt count() -> number { user: "test" }`);
    expect(out).toContain("float(raw)");
  });

  test("boolean return type generates true/false check", () => {
    const out = compile(`@version "1.0.0"\nprompt flag() -> boolean { user: "test" }`);
    expect(out).toContain("lower not in (\"true\", \"false\")");
  });

  test("template {{var}} becomes f-string with input['var']", () => {
    const out = compile(`@version "1.0.0"\nprompt greet(name: string) -> string { user: "Hi {{name}}" }`);
    expect(out).toContain(`{input['name']}`);
    expect(out).toContain('f"');
  });

  test("system section appears in messages", () => {
    const out = compile(`@version "1.0.0"\nprompt greet() -> string { system: "You are a greeter." user: "Hi" }`);
    expect(out).toContain('"role": "system"');
    expect(out).toContain("You are a greeter.");
  });

  test("TypedDict input type name is PascalCase + Input", () => {
    const out = compile(`@version "1.0.0"\nprompt classify_ticket() -> string { user: "test" }`);
    expect(out).toContain("class ClassifyTicketInput(TypedDict):");
  });

  test("type reference return type uses the declared name", () => {
    const out = compile(`
type Category = enum { a, b }
prompt classify() -> Category { user: "test" }`);
    expect(out).toContain("-> Category:");
  });
});

