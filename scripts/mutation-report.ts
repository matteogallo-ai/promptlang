/**
 * Turns Stryker's JSON report into the committed mutation record: per-file
 * scores in docs/mutation/summary.json and docs/mutation/README.md, and the
 * list of surviving mutants that docs/mutation/survivors.md must account for.
 *
 * Usage: bun run scripts/mutation-report.ts [reports/mutation/mutation.json]
 * Run by `bun run mutation` after `stryker run`.
 */
import { readdirSync } from "node:fs";
import { join } from "node:path";

interface Mutant {
  mutatorName: string;
  status: string;
  replacement?: string;
  location: { start: { line: number; column: number } };
}

interface Report {
  files: Record<string, { mutants: Mutant[] }>;
}

export interface FileScore {
  file: string;
  killed: number;
  timeout: number;
  survived: number;
  noCoverage: number;
  /** Mutants that broke compilation or the runner; Stryker leaves them out of the score. */
  errors: number;
  /** (killed + timeout) / (killed + timeout + survived + noCoverage), in percent. */
  score: number;
}

export interface Survivor {
  file: string;
  line: number;
  column: number;
  mutator: string;
  replacement: string;
}

const count = (ms: Mutant[], status: string) => ms.filter((m) => m.status === status).length;

function score(detected: number, valid: number): number {
  return valid === 0 ? 100 : Math.round((detected / valid) * 10_000) / 100;
}

/** Per-file and total scores, using Stryker's own definition of the mutation score. */
export function summarize(report: Report): { files: FileScore[]; total: FileScore } {
  const files = Object.entries(report.files)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([file, { mutants }]): FileScore => {
      const killed = count(mutants, "Killed");
      const timeout = count(mutants, "Timeout");
      const survived = count(mutants, "Survived");
      const noCoverage = count(mutants, "NoCoverage");
      const errors = count(mutants, "CompileError") + count(mutants, "RuntimeError");
      const detected = killed + timeout;
      return {
        file,
        killed,
        timeout,
        survived,
        noCoverage,
        errors,
        score: score(detected, detected + survived + noCoverage),
      };
    });
  const sum = (k: "killed" | "timeout" | "survived" | "noCoverage" | "errors") =>
    files.reduce((n, f) => n + f[k], 0);
  const detected = sum("killed") + sum("timeout");
  const total: FileScore = {
    file: "total",
    killed: sum("killed"),
    timeout: sum("timeout"),
    survived: sum("survived"),
    noCoverage: sum("noCoverage"),
    errors: sum("errors"),
    score: score(detected, detected + sum("survived") + sum("noCoverage")),
  };
  return { files, total };
}

/** Surviving and uncovered mutants, in file then line order. */
export function survivors(report: Report): Survivor[] {
  return Object.entries(report.files)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([file, { mutants }]) =>
      mutants
        .filter((m) => m.status === "Survived" || m.status === "NoCoverage")
        .map((m) => ({
          file,
          line: m.location.start.line,
          column: m.location.start.column,
          mutator: m.mutatorName,
          replacement: (m.replacement ?? "").replace(/\s+/g, " ").slice(0, 60),
        }))
        .sort((a, b) => a.line - b.line || a.column - b.column)
    );
}

/** The `src/<dir>` entries no positive mutate pattern starts in. */
export function unmutated(dirs: readonly string[], mutate: readonly string[]): string[] {
  const reached = mutate.filter((g) => !g.startsWith("!"));
  return dirs.map((d) => `src/${d}`).filter((d) => !reached.some((g) => g.startsWith(`${d}/`)));
}

function row(f: FileScore): string {
  return `| \`${f.file}\` | ${f.score.toFixed(2)} | ${f.killed} | ${f.timeout} | ${f.survived} | ${f.noCoverage} | ${f.errors} |`;
}

if (import.meta.main) {
  const repoRoot = join(import.meta.dir, "..");
  const reportPath = process.argv[2] ?? join(repoRoot, "reports/mutation/mutation.json");
  const report = (await Bun.file(reportPath).json()) as Report;
  const strykerPkg = await Bun.file(
    join(repoRoot, "node_modules/@stryker-mutator/core/package.json")
  ).json();
  const config = await Bun.file(join(repoRoot, "stryker.config.json")).json();
  const { files, total } = summarize(report);
  const date = new Date().toISOString().slice(0, 10);
  const srcDirs = readdirSync(join(repoRoot, "src"), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
  const notMutated = unmutated(srcDirs, config.mutate);

  await Bun.write(
    join(repoRoot, "docs/mutation/summary.json"),
    `${JSON.stringify({ date, stryker: strykerPkg.version, files, total }, null, 2)}\n`
  );
  await Bun.write(
    join(repoRoot, "docs/mutation/README.md"),
    [
      "# Mutation testing",
      "",
      `Generated by \`scripts/mutation-report.ts\` from a Stryker run on ${date}`,
      `(\`@stryker-mutator/core\` ${strykerPkg.version}, Bun ${Bun.version}). Reproduce with:`,
      "",
      "```bash",
      "bun run mutation",
      "```",
      "",
      `Stryker mutates \`${config.mutate.join("`, `")}\` and runs`,
      `\`${config.commandRunner.command}\` against each mutant (command runner,`,
      "no per-test coverage, so every mutant runs the whole command). This runs locally,",
      "not in CI. Score = (killed + timeout) / (killed + timeout + survived + no coverage).",
      "Every surviving mutant is accounted for in [survivors.md](survivors.md).",
      "",
      `The score covers those files only. Not mutated: \`${notMutated.join("`, `")}\`;`,
      "their tests are not measured by this page.",
      "",
      "| File | Score % | Killed | Timeout | Survived | No coverage | Errors |",
      "| ---- | ------: | -----: | ------: | -------: | ----------: | -----: |",
      ...files.map(row),
      row(total).replace("`total`", "**total**"),
      "",
    ].join("\n")
  );
  const left = survivors(report);
  console.log(`mutation score ${total.score}% (${left.length} survivor(s))`);
  for (const s of left) {
    console.log(`  ${s.file}:${s.line}:${s.column}  ${s.mutator}  ${s.replacement}`);
  }
}
